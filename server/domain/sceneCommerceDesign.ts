/** The 自研版 scene has no `params` step: its 套图风格 comes from a `core.code` step whose `fallback`
 * input is a literal, and that step's other input (`analyzed`) is fed by a step gated on
 * `input.reference is_not_empty` — a field that is always empty here, so the literal is what actually
 * ships. It still said 「简洁」, cancelling the v6 density ceiling the same way the 第三方版 default
 * style did. Matched by input key + literal rather than step id, so an unrelated scene is untouched. */

function appendBlock(prompt: string, block: string): string {
  const trimmed = prompt.replace(/\s+$/, "");
  return trimmed ? `${trimmed}\n\n${block}` : block;
}

function changed(workflow: RunWorkflowDefinition, steps: RunStep[], original: readonly RunStep[]): RunWorkflowDefinition {
  return steps.every((step, index) => step === original[index]) ? workflow : { ...workflow, steps };
}

/** The parameter header (套图数量/风格/客户需求…) is scene-specific, so keep it and replace the rest.
 * The shared 图N numbering block is re-inserted directly under that header, where it stays in force. */
function replacePlanBody(prompt: string, numberingBlock: string): string {
  const body = numberingBlock && prompt.endsWith(numberingBlock)
    ? prompt.slice(0, prompt.length - numberingBlock.length).replace(/\s+$/, "")
    : prompt;
  const header = new RegExp(`^[\\s\\S]*?${NEED_LINE.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`, "m").exec(body);
  if (!header) throw new Error(`套图方案提示词缺少「${NEED_LINE}」参数行，无法安全替换设计正文`);
  return [header[0], numberingBlock, COMMERCE_PLAN_DESIGN_BODY].filter(Boolean).join("\n\n");
}

/** Declared output description must match the new card contract, or the run detail shows the old shape. */
export const COMMERCE_CARDS_DESCRIPTION = `[{"id":"01","index":1,"type":"hero","design":"完整电商成图设计：版式、画面、环境、光线、质感、视觉系统、图中文字、约束","copy":["图中文字原文"],"targetLanguage":"英文"}]`;

function alignCardsOutput(step: RunStep, changes: string[]): RunStep {
  const original = step.outputs ?? [];
  const outputs = original.map((output) => {
    if (output.key !== "cards" || output.description === COMMERCE_CARDS_DESCRIPTION) return output;
    return { ...output, description: COMMERCE_CARDS_DESCRIPTION };
  });
  if (!outputs.some((output, index) => output !== original[index])) return step;
  changes.push(`${step.name}：输出说明同步为新卡片契约（type 用 hero/selling_point/detail/lifestyle/mood/specs/package）`);
  return { ...step, outputs };
}

function patchPlanStep(step: RunStep, numberingBlock: string, changes: string[]): RunStep {
  const prompt = step.promptTemplate ?? "";
  // Output alignment is independent of the prompt body: an already-patched draft still needs it.
  // Keyed on the revision, not the family marker: a draft published with the v1 body still contains
  // COMMERCE_DESIGN_MARKER, and must be rewritten or this revision would never reach it.
  const next = prompt.includes(COMMERCE_DESIGN_REVISION)
    ? step
    : { ...step, promptTemplate: replacePlanBody(prompt, numberingBlock) };
  if (next !== step) changes.push(`${step.name}：提示词改为电商成图设计（版式/视觉系统/图中文字），保留全部事实约束与 图N 编号`);
  return alignCardsOutput(next, changes);
}

function patchPromptStep(step: RunStep, changes: string[]): RunStep {
  const prompt = step.promptTemplate ?? "";
  if (prompt.includes(COMMERCE_DESIGN_REVISION)) return step;
  // A v1 draft already appended the whole block, so appending again would stack two copies: replace
  // the old design block in place. The replaced region ends at the next top-level block, so a draft
  // whose 图N block sits after the design block keeps that block instead of losing it.
  const markerAt = prompt.indexOf(COMMERCE_DESIGN_MARKER);
  let head = prompt;
  let tail = "";
  if (markerAt !== -1) {
    const nextBlockAt = prompt.indexOf("\n\n[", markerAt + COMMERCE_DESIGN_MARKER.length);
    head = prompt.slice(0, markerAt);
    tail = nextBlockAt === -1 ? "" : prompt.slice(nextBlockAt).replace(/^\s+/, "");
  }
  const rebuilt = appendBlock(head.replace(/\s+$/, ""), COMMERCE_PROMPT_DESIGN);
  changes.push(`${step.name}：要求完整保留版式、图文层级与图中文字，不得压回商品摄影底图`);
  return { ...step, promptTemplate: tail ? `${rebuilt}\n\n${tail}` : rebuilt };
}

/** Matched by content, not by step id: only the scene that actually ships this default is touched.
 *  Two independent repairs, because run 33dab077 proved the default style alone was not enough:
 *  (a) the default text itself, and (b) the compose expression, which discarded every density word
 *  whenever the client supplied 风格补充. */
function patchStyleStep(step: RunStep, changes: string[]): RunStep {
  const code = step.capabilityConfig?.code;
  if (typeof code !== "string" || !DEFAULT_STYLE_LINE.test(code)) return step;
  let next = code;

  if (!next.includes(COMMERCE_DEFAULT_STYLE_MARKER)) {
    next = next.replace(DEFAULT_STYLE_LINE, `const DEFAULT_STYLE = "${COMMERCE_DEFAULT_STYLE}"; // ${COMMERCE_DEFAULT_STYLE_MARKER}`);
    changes.push(`${step.name}：默认风格改为货架信息密度型，不再与设计正文互相抵消`);
  }

  // Appending the clause to whichever base wins is what makes 风格补充 additive. Guarded on the
  // clause marker so re-running the patch over its own output is a no-op.
  if (STYLE_COMPOSE_LINE.test(next) && !next.includes(COMMERCE_DENSITY_CLAUSE_MARKER)) {
    next = next.replace(
      STYLE_COMPOSE_LINE,
      [
        `const DENSITY_CLAUSE = "${COMMERCE_DENSITY_CLAUSE}"; // ${COMMERCE_DENSITY_CLAUSE_MARKER}`,
        `const BASE_STYLE = analyzed.length > 0 ? analyzed : (hint.length > 0 ? hint : DEFAULT_STYLE);`,
        `const style = BASE_STYLE.includes(DENSITY_CLAUSE) ? BASE_STYLE : BASE_STYLE + "；" + DENSITY_CLAUSE;`,
      ].join("\n"),
    );
    changes.push(`${step.name}：密度要求拼接到实际生效的风格之后（原先用户填了风格补充就整条替换掉默认风格，密度要求丢失）`);
  }

  if (next === code) return step;
  return { ...step, capabilityConfig: { ...step.capabilityConfig, code: next } };
}

/** 自研版 route: keep the `fallback` input literal in step with the current default style.
 *  The v6 pass prefixed COMMERCE_DEFAULT_STYLE (v4 text) onto it, so the literal now already contains
 *  the keyword — a keyword guard would skip it forever and the stale 4–6 figure would survive here
 *  while the body says 5–8. Migrate the v4 text in place when present; otherwise prefix the current
 *  style. Returns the step untouched when the input is not a literal or is already current. */
function patchStyleFallback(step: RunStep, changes: string[]): RunStep {
  const inputs = step.inputs;
  if (!inputs?.length) return step;
  let touched = false;
  let why = "";
  const next = inputs.map((input) => {
    if (input.key !== "fallback" || input.valueSource !== "literal") return input;
    const value = input.literalValue;
    if (typeof value !== "string") return input;
    if (value.includes(COMMERCE_DEFAULT_STYLE)) return input;
    touched = true;
    if (value.includes(COMMERCE_DEFAULT_STYLE_V4)) {
      why = `${step.name}：风格字面量里的 v4 默认风格迁到 v5（数字改由设计正文单点定义）`;
      return { ...input, literalValue: value.replace(COMMERCE_DEFAULT_STYLE_V4, COMMERCE_DEFAULT_STYLE) };
    }
    why = `${step.name}：风格字面量补上货架信息密度型要求（原先只说「简洁」，与设计正文互相抵消）`;
    return { ...input, literalValue: `${COMMERCE_DEFAULT_STYLE}；${value}` };
  });
  if (!touched) return step;
  changes.push(why);
  return { ...step, inputs: next };
}

/** Idempotent. `numberingBlock` is the block sceneReferenceImageNumbering appends, preserved as-is. */
export function applyCommerceDesign(workflow: RunWorkflowDefinition, numberingBlock: string): { workflow: RunWorkflowDefinition; changes: string[] } {
  const changes: string[] = [];
  const original = workflow.steps ?? [];
  const steps = original.map((step) => {
    if (step.id === COMMERCE_PLAN_STEP_ID) return patchPlanStep(step, numberingBlock, changes);
    if (step.id === COMMERCE_PROMPT_STEP_ID) return patchPromptStep(step, changes);
    return patchStyleFallback(patchStyleStep(step, changes), changes);
  });
  return { workflow: changed(workflow, steps, original), changes };
}
