export type AiGuideSection = {
  /** 稳定节号：取标题前导编号（"9." → "9"、"10.2 日志查看" → "10.2"）；无编号子节按父节顺序编号。 */
  id: string;
  /** 标题（已去掉前导编号）。 */
  title: string;
  /** 该节正文（含标题行与全部子节），不改写任何字符。 */
  text: string;
  /** 分节资源地址 zane://guide/<节号>。 */
  uri: string;
  bytes: number;
  /** 子节（"### "）节号：子节正文单独成节，父节正文仍完整包含它们。 */
  childIds: string[];
  parentId?: string;
};

/** 标题前导编号（"10.2 日志查看" → "10.2"）；标题没有编号时返回 undefined。 */
function guideHeadingId(title: string): string | undefined {
  return /^([0-9]+(?:\.[0-9]+)*)[.、\s]/.exec(title)?.[1];
}

function guideTitleText(title: string): string {
  return title.replace(/^[0-9]+(?:\.[0-9]+)*[.、\s]\s*/, "").trim() || title;
}

/** 按 "## " 分节、"### " 分子节：正文逐行归属，拼接后与原文逐字节相同。 */
export function parseGuideSections(body: string): AiGuideSection[] {
  type Draft = { id: string; title: string; lines: string[]; childIds: string[]; children: Draft[]; parentId?: string };
  const drafts: Draft[] = [];
  const ids = new Set<string>();
  const claim = (id: string, title: string) => {
    if (ids.has(id)) throw new Error("AI 手册节号冲突：" + id + "（" + title + "）；请调整标题编号后重试");
    ids.add(id);
    return id;
  };
  let parent: Draft | undefined;
  let active: Draft | undefined;
  let childCount = 0;
  for (const line of body.split("\n")) {
    const heading = /^## (?!#)(.+)$/.exec(line);
    if (heading) {
      const title = heading[1].trim();
      parent = { id: claim(guideHeadingId(title) ?? "s" + (drafts.length + 1), title), title: guideTitleText(title), lines: [line], childIds: [], children: [] };
      active = parent; childCount = 0; drafts.push(parent);
      continue;
    }
    const subheading = /^### (.+)$/.exec(line);
    if (subheading && parent) {
      const title = subheading[1].trim();
      childCount += 1;
      const child: Draft = { id: claim(guideHeadingId(title) ?? parent.id + "." + childCount, title), title: guideTitleText(title), lines: [line], childIds: [], children: [], parentId: parent.id };
      parent.childIds.push(child.id); parent.children.push(child); active = child; drafts.push(child);
      continue;
    }
    active?.lines.push(line);
  }
  const encoder = new TextEncoder();
  // 父节正文 = 本节行 + 全部子节正文：读父节号拿到该主题的完整内容，读子节号只拿该子节。
  const textOf = (draft: Draft): string => [draft.lines.join("\n"), ...draft.children.map(textOf)].join("\n");
  return drafts.map(draft => {
    const text = textOf(draft);
    return { id: draft.id, title: draft.title, text, uri: "zane://guide/" + draft.id, bytes: encoder.encode(text).length, childIds: draft.childIds, ...(draft.parentId ? { parentId: draft.parentId } : {}) };
  });
}

